// ── Keep dynamic content translated ──
// popup.js (and other views) rewrite text nodes AFTER the initial pass, which would
// snap the UI back to English. Re-run applyTranslations on any DOM mutation, with the
// observer disconnected during the pass (so our own edits don't re-trigger it) and a
// debounce to coalesce bursts of rapid updates.
if (_currentLang !== 'en' && typeof MutationObserver !== 'undefined') {
  let _pending = false;
  const _observer = new MutationObserver(() => {
    if (_pending) return;
    _pending = true;
    requestAnimationFrame(() => {
      _pending = false;
      _observer.disconnect();
      try { applyTranslations(); } finally {
        _observer.observe(document.body, { childList: true, subtree: true, characterData: true });
      }
    });
  });
  _observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}

